#!/usr/bin/env python3
"""Writes src/data.rs from tests/fixtures/registry.json (the original's registry).

Run after `bun rust/platforms-rs/tests/make-fixtures.ts`.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
reg = json.loads((HERE / "fixtures" / "registry.json").read_text())

def s(v):
    return json.dumps(v, ensure_ascii=False)

def strs(v):
    return "&[" + ", ".join(s(x) for x in v) + "]"

def opt(v, f):
    return "None" if v is None else f"Some({f(v)})"

PATH_KEYS = ["instructions", "legacy_instructions", "skills", "rules", "legacy_rules", "mcp",
             "permissions", "hooks", "agents", "commands", "settings", "plugins"]
ALT_KEYS = ["commands", "agents", "rules", "instructions", "skills", "settings"]

def alternates(a):
    unknown = set(a) - set(ALT_KEYS)
    assert not unknown, unknown
    fields = "".join(f"{k}: {opt(a.get(k), strs)}, " for k in ALT_KEYS)
    return f"PathAlternates {{ {fields}}}"

def paths(p):
    unknown = set(p) - set(PATH_KEYS) - {"pathAlternates"}
    assert not unknown, unknown
    fields = "".join(f"{k}: {opt(p.get(k), s)}, " for k in PATH_KEYS)
    fields += f"path_alternates: {opt(p.get('pathAlternates'), alternates)}, "
    return f"PlatformPaths {{ {fields}}}"

def related(rs):
    return "&[" + ", ".join(f"RelatedLocation {{ path: {s(r['path'])}, surfaces: {strs(r['surfaces'])} }}" for r in rs) + "]"

def detection(d):
    return f"DetectionPaths {{ project: {opt(d.get('project'), strs)}, global: {opt(d.get('global'), strs)} }}"

KNOWN = {"id", "name", "supports", "projectPaths", "globalPaths", "skillEmission", "hostManagedPaths",
         "relatedLocations", "hostPluginRuntimeModules", "detectionPaths"}
out = ["//! Generated by `tests/gen-data.py` from the original's registry. Do not edit.",
       "",
       "use crate::*;",
       "",
       "#[rustfmt::skip]",
       "pub(crate) static PLATFORMS: &[PlatformDefinition] = &["]
for p in reg["platforms"]:
    assert not set(p) - KNOWN, set(p) - KNOWN
    hmp = p.get("hostManagedPaths")
    out.append("    PlatformDefinition {")
    out.append(f"        id: {s(p['id'])},")
    out.append(f"        name: {s(p['name'])},")
    out.append(f"        supports: {strs(p['supports'])},")
    out.append(f"        project_paths: {paths(p['projectPaths'])},")
    out.append(f"        global_paths: {paths(p['globalPaths'])},")
    out.append(f"        skill_emission: {opt(p.get('skillEmission'), s)},")
    out.append(f"        host_managed_paths: {opt(hmp, lambda h: 'HostManagedPaths { skills: ' + opt(h.get('skills'), s) + ' }')},")
    out.append(f"        related_locations: {opt(p.get('relatedLocations'), related)},")
    out.append(f"        host_plugin_runtime_modules: {'true' if p.get('hostPluginRuntimeModules') else 'false'},")
    out.append(f"        detection_paths: {opt(p.get('detectionPaths'), detection)},")
    out.append("    },")
out.append("];")
(HERE.parent / "src" / "data.rs").write_text("\n".join(out) + "\n")
print(f"wrote {len(reg['platforms'])} platforms")
