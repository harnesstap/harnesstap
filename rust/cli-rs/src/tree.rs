//! The original's commander tree, as `tests/dump-tree.ts` dumps it into `data/tree.json`.

use std::collections::HashMap;
use std::sync::OnceLock;

use serde::Deserialize;

#[derive(Debug, Clone, Deserialize)]
pub struct Opt {
    pub flags: String,
    pub attribute_name: String,
    #[serde(default)]
    pub default_value: Option<serde_json::Value>,
    pub negate: bool,
    pub custom_parser: bool,
    pub short: Option<String>,
    pub long: Option<String>,
    /// Takes a value (`<value>`).
    pub required: bool,
    /// Takes an optional value (`[value]`).
    pub optional: bool,
    pub variadic: bool,
    pub mandatory: bool,
    pub choices: Option<Vec<String>>,
    pub env_var: Option<String>,
    pub conflicts: bool,
    pub implied: bool,
    pub preset: bool,
}

impl Opt {
    /// commander's `Option.is`.
    pub fn is(&self, arg: &str) -> bool {
        self.short.as_deref() == Some(arg) || self.long.as_deref() == Some(arg)
    }
}

#[derive(Debug, Clone, Deserialize)]
pub struct Argument {
    pub name: String,
    #[serde(default)]
    pub default_value: Option<serde_json::Value>,
    pub required: bool,
    pub variadic: bool,
    pub choices: Option<Vec<String>>,
}

#[derive(Debug, Clone, Deserialize)]
pub struct HelpOption {
    pub short: Option<String>,
    pub long: Option<String>,
}

#[derive(Debug, Clone, Deserialize)]
pub struct Node {
    pub name: String,
    pub aliases: Vec<String>,
    pub has_action: bool,
    pub group_help_action: bool,
    pub allow_unknown_option: bool,
    pub allow_excess_arguments: bool,
    pub positional_options: bool,
    pub pass_through: bool,
    pub combine_flag_and_optional_value: bool,
    pub default_command: Option<String>,
    pub help_option: Option<HelpOption>,
    pub help_command: Option<String>,
    pub exit_override: bool,
    pub output_error_silenced: bool,
    pub show_help_after_error: bool,
    pub unsupported: bool,
    pub options: Vec<Opt>,
    pub arguments: Vec<Argument>,
    pub suggest_commands: Vec<String>,
    pub suggest_options: Vec<String>,
    pub help: String,
    pub commands: Vec<Node>,
}

impl Node {
    /// commander's `_findCommand`.
    pub fn find_command(&self, name: &str) -> Option<&Node> {
        if name.is_empty() {
            return None;
        }
        self.commands
            .iter()
            .find(|c| c.name == name || c.aliases.iter().any(|a| a == name))
    }

    /// commander's `_findOption`.
    pub fn find_option(&self, arg: &str) -> Option<usize> {
        self.options.iter().position(|o| o.is(arg))
    }

    pub fn wants_help(&self, arg: &str) -> bool {
        self.help_option
            .as_ref()
            .is_some_and(|h| h.short.as_deref() == Some(arg) || h.long.as_deref() == Some(arg))
    }

    /// Anything in this subtree the port does not reproduce.
    pub fn uses_unported_features(&self) -> bool {
        self.unsupported
            || !self.exit_override
            || !self.output_error_silenced
            || self.show_help_after_error
            || self.default_command.is_some()
            || self
                .options
                .iter()
                .any(|o| o.env_var.is_some() || o.conflicts || o.implied || o.preset)
            || self.commands.iter().any(|c| c.name == "*")
            || self.commands.iter().any(Node::uses_unported_features)
    }
}

#[derive(Debug, Deserialize)]
pub struct CatalogEntry {
    pub name: String,
    pub aliases: Vec<String>,
    pub loader: String,
}

#[derive(Debug, Deserialize)]
pub struct Tree {
    pub root: Node,
    pub root_help: String,
    pub catalog: Vec<CatalogEntry>,
    pub top_level_tokens: Vec<String>,
    pub loaders: HashMap<String, Vec<Node>>,
}

pub fn tree() -> &'static Tree {
    static TREE: OnceLock<Tree> = OnceLock::new();
    TREE.get_or_init(|| {
        // INFALLIBLE: the file is generated by tests/dump-tree.ts and checked by the tests.
        serde_json::from_str(include_str!("../data/tree.json")).expect("data/tree.json parses")
    })
}

impl Tree {
    /// `findCatalogEntry` (`src/cli/command-catalog.ts`).
    pub fn catalog_loader(&self, token: &str) -> Option<&str> {
        self.catalog
            .iter()
            .find(|e| e.name == token || e.aliases.iter().any(|a| a == token))
            .map(|e| e.loader.as_str())
    }

    /// The root as commander sees it once `ensureCommandsForArgv` loaded `loader`.
    pub fn root_with(&self, loader: Option<&str>) -> Node {
        let mut root = self.root.clone();
        root.commands = loader
            .and_then(|id| self.loaders.get(id))
            .cloned()
            .unwrap_or_default();
        root
    }
}
