//! `help` and `help scenario` (`src/cli/commands/help.ts`, `services/concepts-guide.ts`,
//! `services/scenario-guide.ts`, the scenarios from `src/generated/scenarios.ts`).

use std::sync::OnceLock;

use regex::Regex;
use serde::Deserialize;
use serde_json::{Value, json};

use super::{Format, Printed, output_format, print_json};
use crate::commander::ActionCall;

const GUIDE_SCENARIOS_URL: &str =
    "https://github.com/harnesstap/harnesstap/blob/main/docs/scenarios/scenarios.md";
const CANONICAL_CATALOG_BASELINE: &str = "engineering-foundation";
const CANONICAL_CATALOG_SEARCH_HINT: &str = "foundation";

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Scenario {
    id: u32,
    filename: String,
    title: String,
    frequency: Option<String>,
    status: Option<String>,
    summary_lines: Vec<String>,
    commands: Vec<String>,
}

fn scenarios() -> &'static [Scenario] {
    static DATA: OnceLock<Vec<Scenario>> = OnceLock::new();
    DATA.get_or_init(|| {
        // INFALLIBLE: generated by tests/dump-tree.ts and read by the tests.
        serde_json::from_str(include_str!("../../data/scenarios.json"))
            .expect("data/scenarios.json")
    })
}

/// `plainTerminalText` (`src/copy/cli.ts`): markdown links to `label (url)` or `label`.
fn plain_terminal_text(value: &str) -> String {
    static LINK: OnceLock<Regex> = OnceLock::new();
    // INFALLIBLE: a constant pattern.
    let link = LINK.get_or_init(|| Regex::new(r"\[([^\]]+)\]\(([^)]+)\)").expect("pattern"));
    link.replace_all(value, |c: &regex::Captures<'_>| {
        let (label, target) = (&c[1], &c[2]);
        if target.starts_with("http://") || target.starts_with("https://") {
            format!("{label} ({target})")
        } else {
            label.to_string()
        }
    })
    .into_owned()
}

/// `formatScenarioCommand` and `formatCommand(string)` (`src/cli/shared.ts`).
fn format_command(path: &str) -> String {
    let trimmed = emit_rs::js::trim(path);
    let stripped = ["harnesstap", "ht"]
        .iter()
        .find_map(|p| {
            let rest = trimmed.strip_prefix(p)?;
            let after = rest.trim_start_matches(emit_rs::js::is_space);
            (after.len() < rest.len()).then_some(after)
        })
        .unwrap_or(trimmed);
    if stripped.is_empty() {
        "ht".to_string()
    } else {
        format!("ht {stripped}")
    }
}

fn meta(scenario: &Scenario) -> String {
    [
        scenario.frequency.clone(),
        scenario.status.as_deref().map(plain_terminal_text),
    ]
    .into_iter()
    .flatten()
    .filter(|s| !s.is_empty())
    .collect::<Vec<_>>()
    .join(" · ")
}

fn concepts_payload() -> Value {
    let pair = |a: &str, b: &str| json!({ "term": a, "definition": b });
    let cmd = |a: String, b: &str| json!({ "command": a, "purpose": b });
    json!({
        "concepts": [
            pair("resource", "Single canonical item (skill, rule, MCP, hook, agent, ...)"),
            pair("plugin", "Named bundle of resources you apply to projects"),
            pair("profile", "Plugin tagged profile; apply globally with profile use"),
            pair("account", "HarnessTap Cloud login identity stored locally"),
            pair("environment", "Named how-values (vars, secrets, model config)"),
            pair("harness", "Target CLI (claude-code, codex, cursor, ...)"),
        ],
        "harness_roles": [
            pair("registered", "Harnesses HarnessTap writes to (harness set --harnesses)"),
            pair("default", "First registered harness: mirror source and scans when none is named"),
        ],
        "commands": [
            cmd("plugin apply <plugin>".into(), "Materialize plugins onto a project"),
            cmd("profile use <profile>".into(), "Apply a profile plugin globally to home harness files"),
            cmd("migrate export <archive>".into(), "Share your full local workspace with another machine"),
            cmd("mirror .".into(), "Sync registered harnesses from the first registered one on disk"),
            cmd(format!("plugin list --search {CANONICAL_CATALOG_SEARCH_HINT} --remote-only"), "Browse public catalog plugins"),
            cmd(format!("plugin pull org/catalog/{CANONICAL_CATALOG_BASELINE}"), "Cache a catalog plugin locally"),
            cmd("plugin edit <plugin> --add <item> --type skill".into(), "Add a local resource to a plugin"),
        ],
        "environment_cascade": "home env ◂ plugin default env (last wins on apply)",
    })
}

pub(super) fn help(call: &ActionCall) -> Printed {
    let format = match output_format(call) {
        Ok(format) => format,
        Err(printed) => return printed,
    };
    let concepts = concepts_payload();
    if let Format::Json = format {
        let summaries: Vec<Value> = scenarios()
            .iter()
            .map(|s| json!({ "id": s.id, "title": s.title, "frequency": s.frequency, "status": s.status }))
            .collect();
        return print_json(&json!({ "concepts": concepts, "scenarios": summaries }));
    }
    let mut out = String::new();
    let mut line = |s: &str| {
        out.push_str(s);
        out.push('\n');
    };
    let pad13 = |s: &str| format!("{s:<13}");
    for (title, key) in [
        ("CORE CONCEPTS", "concepts"),
        ("HARNESS ROLES", "harness_roles"),
    ] {
        line("");
        line(title);
        line("");
        for entry in concepts[key].as_array().into_iter().flatten() {
            line(&format!(
                "  {} {}",
                pad13(entry["term"].as_str().unwrap_or_default()),
                entry["definition"].as_str().unwrap_or_default()
            ));
        }
    }
    line("");
    line("COMMON COMMANDS");
    line("");
    for entry in concepts["commands"].as_array().into_iter().flatten() {
        line(&format!(
            "  {}  {}",
            format_command(entry["command"].as_str().unwrap_or_default()),
            entry["purpose"].as_str().unwrap_or_default()
        ));
    }
    line("");
    line("ENVIRONMENT CASCADE");
    line("");
    line(&format!(
        "  {}",
        concepts["environment_cascade"].as_str().unwrap_or_default()
    ));
    line("");
    line("SCENARIOS");
    line("");
    let width = scenarios()
        .iter()
        .map(|s| s.id.to_string().len())
        .max()
        .unwrap_or(0);
    for scenario in scenarios() {
        let meta = meta(scenario);
        let suffix = if meta.is_empty() {
            String::new()
        } else {
            format!("  {meta}")
        };
        line(&format!(
            "  {:>width$}  {}{suffix}",
            scenario.id, scenario.title
        ));
    }
    line("");
    line("Run ht help scenario <id> for a scenario playbook.");
    Printed {
        stdout: out,
        stderr: String::new(),
        code: 0,
        themed: true,
    }
}

/// `parseScenarioId`: `Number.parseInt(input.trim(), 10)`, then finite and at least 1.
fn parse_scenario_id(input: &str) -> Result<f64, String> {
    let trimmed = emit_rs::js::trim(input);
    let (sign, rest) = match trimmed.as_bytes().first() {
        Some(b'-') => (-1.0, &trimmed[1..]),
        Some(b'+') => (1.0, &trimmed[1..]),
        _ => (1.0, trimmed),
    };
    let digits: String = rest.chars().take_while(char::is_ascii_digit).collect();
    let invalid = || format!("Invalid scenario id: {input}");
    if digits.is_empty() {
        return Err(invalid());
    }
    let id = sign * digits.parse::<f64>().map_err(|_| invalid())?;
    if !id.is_finite() || id < 1.0 {
        return Err(invalid());
    }
    Ok(id)
}

pub(super) fn scenario(call: &ActionCall) -> Printed {
    let format = match output_format(call) {
        Ok(format) => format,
        Err(printed) => return printed,
    };
    let input = call
        .args
        .first()
        .and_then(Value::as_str)
        .unwrap_or_default();
    let found = parse_scenario_id(input).and_then(|id| {
        scenarios()
            .iter()
            .find(|s| f64::from(s.id) == id)
            .ok_or_else(|| {
                let shown = emit_rs::js::number_to_string(
                    &serde_json::Number::from_f64(id).unwrap_or_else(|| 0.into()),
                );
                format!("Scenario not found: {shown}")
            })
    });
    let scenario = match found {
        Ok(scenario) => scenario,
        Err(message) => {
            let stderr = format!(
                "{}\nht help scenario 11\nSee {GUIDE_SCENARIOS_URL}\n",
                crate::ensure_error_prefix(&message)
            );
            return Printed {
                stdout: String::new(),
                stderr,
                code: 1,
                themed: false,
            };
        }
    };
    if let Format::Json = format {
        return print_json(&json!({
            "id": scenario.id,
            "filename": scenario.filename,
            "title": scenario.title,
            "frequency": scenario.frequency,
            "status": scenario.status,
            "summaryLines": scenario.summary_lines,
            "commands": scenario.commands,
        }));
    }
    let mut out = String::new();
    let mut line = |s: &str| {
        out.push_str(s);
        out.push('\n');
    };
    line("");
    line(&format!(
        "SCENARIO {}: {}",
        scenario.id,
        scenario.title.to_uppercase()
    ));
    if scenario.frequency.is_some() || scenario.status.is_some() {
        line("");
        line(&meta(scenario));
    }
    if !scenario.summary_lines.is_empty() {
        line("");
        for summary in &scenario.summary_lines {
            line(&format!("  {}", plain_terminal_text(summary)));
        }
    }
    if !scenario.commands.is_empty() {
        line("");
        line("TYPICAL COMMANDS");
        line("");
        for command in &scenario.commands {
            line(&format!("  {}", format_command(command)));
        }
    }
    line("");
    line(&format!(
        "Full doc: https://github.com/harnesstap/harnesstap/blob/main/docs/scenarios/details/{}",
        scenario.filename
    ));
    line(&format!("All scenarios: {GUIDE_SCENARIOS_URL}"));
    Printed {
        stdout: out,
        stderr: String::new(),
        code: 0,
        themed: true,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scenario_ids_parse_like_parse_int() {
        assert_eq!(parse_scenario_id(" 11abc"), Ok(11.0));
        assert_eq!(parse_scenario_id("+7"), Ok(7.0));
        assert!(parse_scenario_id("0").is_err());
        assert!(parse_scenario_id("-3").is_err());
        assert!(parse_scenario_id("x1").is_err());
    }

    #[test]
    fn links_become_plain_text() {
        assert_eq!(
            plain_terminal_text("see [a](https://x.y) or [b](c.md)"),
            "see a (https://x.y) or b"
        );
    }
}
